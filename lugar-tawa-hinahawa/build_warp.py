#!/usr/bin/env python3
"""Time-warp a story authored on an old voice take onto a new take.
usage: python3 build_warp.py work/words_v1.json work/words.json OLD_TOTAL NEW_TOTAL
Matches identical words between the two takes (difflib) and writes anchor pairs [newFrame, oldFrame]
to web/warp.js (used by main.js: frames of the new take -> frames of the old story timeline) and
work/warp.json (used by audio.py: old cue frames -> new frames)."""
import json, sys, re, difflib
old = json.load(open(sys.argv[1])); new = json.load(open(sys.argv[2])); OT = int(sys.argv[3]); NT = int(sys.argv[4])
norm = lambda w: re.sub(r'[^\w]', '', w['word'].lower())
a = [norm(w) for w in old]; b = [norm(w) for w in new]
sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
pairs = [(0, 0)]
for blk in sm.get_matching_blocks():
    if blk.size < 2: continue  # single-word matches ("si", "ang") can jump to the wrong place
    for k in range(blk.size):
        o, n = old[blk.a + k], new[blk.b + k]
        pairs.append((round(n['start'] * 30, 2), round(o['start'] * 30, 2)))
        pairs.append((round(n['end'] * 30, 2), round(o['end'] * 30, 2)))
pairs.append((NT, OT))
pairs = sorted(set(pairs))
clean = []
for n, o in pairs:  # keep both columns strictly increasing
    if not clean or (n > clean[-1][0] and o > clean[-1][1]): clean.append((n, o))
json.dump(clean, open('work/warp.json', 'w'))
open('web/warp.js', 'w').write('// generated by build_warp.py: [newFrame, oldFrame] anchors\nexport const WARP = ' + json.dumps(clean) + ';\n'
  'export const warp = (f) => { const W = WARP; if (f <= W[0][0]) return W[0][1]; for (let i = 1; i < W.length; i++) if (f <= W[i][0]) { const [n0, o0] = W[i - 1], [n1, o1] = W[i]; return o0 + (o1 - o0) * (f - n0) / (n1 - n0); } return W[W.length - 1][1] + (f - W[W.length - 1][0]); };\n')
print(len(clean), 'anchors; matched words', sum(bk.size for bk in sm.get_matching_blocks()), 'of', len(b))
